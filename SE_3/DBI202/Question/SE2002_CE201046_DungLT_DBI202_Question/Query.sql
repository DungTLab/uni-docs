USE QLSV;
GO

SELECT * FROM SINHVIEN
WHERE YEAR(Ngaysinh) = 1997;
GO

SELECT * FROM SINHVIEN
WHERE YEAR(Ngaysinh) < 1997 
  AND Ten LIKE N'H%';
GO

SELECT SV.*
FROM SINHVIEN SV
JOIN LOP L ON SV.Malop = L.Malop
WHERE L.Sosv > 30;
GO


SELECT * FROM SINHVIEN
WHERE YEAR(Ngaysinh) BETWEEN 1996 AND 1998
  AND Diachi LIKE N'%Cần Thơ%';
GO