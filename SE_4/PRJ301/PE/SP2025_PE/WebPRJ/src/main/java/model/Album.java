package model;

/**
 *
 * @author DungLT
 */
public class Album {

    private int albumId;
    private Artist artist;
    private String title;

    public Album(int albumId, Artist artist, String title) {
        this.albumId = albumId;
        this.artist = artist;
        this.title = title;
    }

    public Album() {
    }

    public int getAlbumId() {
        return albumId;
    }

    public void setAlbumId(int albumId) {
        this.albumId = albumId;
    }

    public Artist getArtist() {
        return artist;
    }

    public void setArtist(Artist artist) {
        this.artist = artist;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

}
